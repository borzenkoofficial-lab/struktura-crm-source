const { contextBridge, ipcRenderer } = require('electron');
contextBridge.exposeInMainWorld('crm', {
  summary: () => ipcRenderer.invoke('dashboard:summary'),
  getNotificationSettings: () => ipcRenderer.invoke('notifications:getSettings'),
  saveNotificationSettings: (data) => ipcRenderer.invoke('notifications:saveSettings', data),
  listClients: () => ipcRenderer.invoke('clients:list'),
  createClient: (data) => ipcRenderer.invoke('clients:create', data),
  listLeads: () => ipcRenderer.invoke('leads:list'),
  createLead: (data) => ipcRenderer.invoke('leads:create', data),
  listProjects: () => ipcRenderer.invoke('projects:list'),
  createProject: (data) => ipcRenderer.invoke('projects:create', data),
  createProjectWithPlan: (data) => ipcRenderer.invoke('projects:createWithPlan', data),
  productionOverview: () => ipcRenderer.invoke('production:overview'),
  exportProductionReportPdf: (data) => ipcRenderer.invoke('production:exportReportPdf', data),
  productionRateModels: (catalogIds, targetCrewSize) => ipcRenderer.invoke('production:rateModels', { catalog_ids: catalogIds, target_crew_size: targetCrewSize }),
  getProductionPlan: (projectId) => ipcRenderer.invoke('production:getPlan', projectId),
  saveProductionPlan: (data) => ipcRenderer.invoke('production:savePlan', data),
  saveWorkShift: (data) => ipcRenderer.invoke('production:saveShift', data),
  deleteWorkShift: (shiftId) => ipcRenderer.invoke('production:deleteShift', shiftId),
  listPayments: () => ipcRenderer.invoke('payments:list'),
  createPayment: (data) => ipcRenderer.invoke('payments:create', data),
  listExpenses: () => ipcRenderer.invoke('expenses:list'),
  financeInsights: () => ipcRenderer.invoke('finance:insights'),
  listTasks: (filter) => ipcRenderer.invoke('tasks:list', filter),
  createTask: (data) => ipcRenderer.invoke('tasks:create', data),
  completeTask: (data) => ipcRenderer.invoke('tasks:complete', data),
  createExpense: (data) => ipcRenderer.invoke('expenses:create', data),
  listProspects: () => ipcRenderer.invoke('prospects:list'),
  searchStatus: () => ipcRenderer.invoke('search:status'),
  saveSearchKey: (data) => ipcRenderer.invoke('search:saveKey', data),
  searchProspects: (data) => ipcRenderer.invoke('search:run', data),
  crawlProspectWebsites: (data) => ipcRenderer.invoke('prospects:crawlWebsites', data),
  createProspect: (data) => ipcRenderer.invoke('prospects:create', data),
  updateProspect: (data) => ipcRenderer.invoke('prospects:update', data),
  convertProspectToLead: (id) => ipcRenderer.invoke('prospects:convertLead', id),
  importProspectsCsv: () => ipcRenderer.invoke('prospects:importCsv'),
  exportDataCsv: (kind) => ipcRenderer.invoke('data:exportCsv', kind),
  createBackup: () => ipcRenderer.invoke('backup:create'),
  restoreBackup: () => ipcRenderer.invoke('backup:restore'),
  openDataFolder: () => ipcRenderer.invoke('app:openDataFolder'),
  openExternal: (url) => ipcRenderer.invoke('app:openExternal', url),
  browserState: () => ipcRenderer.invoke('browser:state'),
  setBrowserVisibility: (data) => ipcRenderer.invoke('browser:visibility', data),
  setBrowserBounds: (data) => ipcRenderer.invoke('browser:setBounds', data),
  navigateBrowser: (data) => ipcRenderer.invoke('browser:navigate', data),
  browserBack: () => ipcRenderer.invoke('browser:back'),
  browserForward: () => ipcRenderer.invoke('browser:forward'),
  browserReload: () => ipcRenderer.invoke('browser:reload'),
  saveBrowserSite: () => ipcRenderer.invoke('browser:saveSite'),
  saveAndScanBrowserSite: (data) => ipcRenderer.invoke('browser:saveAndScan', data),
  onBrowserState: (callback) => { const listener = (_event, state) => callback(state); ipcRenderer.on('browser:state', listener); return () => ipcRenderer.removeListener('browser:state', listener); },
  exportQuotePdf: (data) => ipcRenderer.invoke('estimate:exportQuotePdf', data),
  version: () => ipcRenderer.invoke('app:version'),
  checkForUpdates: () => ipcRenderer.invoke('updates:check'),
  updateStatus: () => ipcRenderer.invoke('updates:status'),
  downloadUpdate: () => ipcRenderer.invoke('updates:download'),
  installUpdate: () => ipcRenderer.invoke('updates:install'),
  onUpdateStatus: (callback) => { const listener = (_event, status) => callback(status); ipcRenderer.on('updates:status', listener); return () => ipcRenderer.removeListener('updates:status', listener); }
});
